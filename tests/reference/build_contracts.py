def _rights_sentence(rights: list[str]) -> str:
    if not rights:
        return ""
    return f" Needs the key right {' or '.join(rights)}."


def describe(row: dict[str, Any], spec: dict[str, Any] | None) -> str:
    text = plan.DESCRIPTIONS[row["operation_id"]]
    if spec and spec.get("combined_paging"):
        text += (
            " Agnum documents its paging here only as one limit/offset parameter, so the step "
            "sends none and returns what Agnum returns in one answer."
        )
    if spec and spec.get("at_least_one"):
        text += " Give at least one filter."
    if row["kind"] == "search":
        text += " Nothing found is an empty list."
    if row["path"] == "/api/products/price":
        text += " " + PRICE_NOTE
    if row["kind"] == "create":
        text += " Running the step again creates the record again."
        if row["operation_id"] == "orders_create":
            text += " Create sales document if new stops at a number Agnum already has."
        if row["operation_id"] == "receipts_create":
            text += " Create purchase receipt if new stops at a number Agnum already has."
    if row["danger"] == "irreversible":
        text += " " + plan.IRREVERSIBLE[(row["method"], row["path"])]
    if row["danger"] == "delete":
        text += (
            " Only the norm whose ID is given; Agnum refuses a norm in use (nothing is deleted "
            "then). Deletion cannot be undone."
        )
    return (text + _rights_sentence(row["rights"]))[:1000]


def generated_step(
    row: dict[str, Any], op: dict[str, Any]
) -> tuple[dict[str, Any], dict[str, Any]]:
    """(step spec for the contracts, registry entry for the runtime)."""
    path_nodes = nodes.path_nodes(op)
    query = nodes.query_nodes(op)
    search = nodes.search_spec(op) if row["kind"] == "search" else None
    body = nodes.body_nodes(op, row) if row["kind"] in plan.WRITE_KINDS else None
    inputs = [input_of(n) for n in path_nodes] + [input_of(n) for n in query]
    if search:
        inputs += search_inputs(search)
    if body is not None:
        if body["name"]:  # a list body: one input
            inputs.append(input_of(body, title="Prices"))
        else:
            inputs += [input_of(n) for n in body["children"]]
    names = [i["name"] for i in inputs]
    if len(names) != len(set(names)):  # pragma: no cover - a builder mistake
        raise SystemExit(f"{row['operation_id']} has clashing inputs: {names}")
    record: dict[str, Any] = {
        "method": row["method"],
        "path": row["path"],
        "kind": row["kind"],
        "answer": answer_kind(op),
        "path_params": path_nodes,
        "query": query,
        "search": search,
        "body": body,
        "danger": row["danger"],
        "objects": row["objects"],
        "single_object": row["objects"] == "one",
        "strict": bool(row["danger"]),
        "no_effect": row["no_effect"],
        "price_note": row["path"] == "/api/products/price",
    }
    step = {
        "operation_id": row["operation_id"],
        "display_name": row["title"],
        "kind": "action" if row["kind"] in plan.WRITE_KINDS else "source",
        "group": row["group"],
        "danger": row["danger"],
        "read": row["kind"] in READ_KINDS,
        "calls": [f"{row['method']} {row['path']}"],
        "description": describe(row, search),
        "inputs": inputs,
        "outputs": outputs_for(row, op),
    }
    return step, record


def all_steps() -> tuple[list[dict[str, Any]], dict[str, dict[str, Any]]]:
    ops = {(o["method"], o["path"]): o for o in plan.operations()}
    registry: dict[str, dict[str, Any]] = {}
    generated: list[dict[str, Any]] = []
    for row in plan.plan():
        step, record = generated_step(row, ops[(row["method"], row["path"])])
        generated.append(step)
        registry[row["operation_id"]] = record
    by_id = {s["operation_id"]: s["inputs"] for s in generated}
    everyday = [
        {**spec, "group": "everyday", "danger": "", "read": spec["kind"] == "source"}
        for spec in composite_specs.steps(by_id)
    ]
    order = {g: i for i, (g, _) in enumerate(GROUPS)}
    generated.sort(
        key=lambda s: (
            order[s["group"]],
            DANGER_ORDER[s["danger"]],
            0 if s["read"] else 1,
            s["display_name"],
        )
    )
    # The PDF step leads the generated steps, right after the everyday ones.
    return everyday + generated, registry


# -- contracts ----------------------------------------------------------------------------------


def errors_for(spec: dict[str, Any]) -> list[str]:
    codes = [*BASE_ERRORS, *TRANSPORT_ERRORS]
    if spec["kind"] == "action":
        codes.append("timeout_unknown")
    if any(o["value_type"] == "artifact_handle" for o in spec["outputs"]):
        codes.append("artifact_output_unavailable")
    return codes


def _clean(item: dict[str, Any]) -> dict[str, Any]:
    return {k: v for k, v in item.items() if k != "placeholder"}


def operation(spec: dict[str, Any]) -> dict[str, Any]:
    write = spec["kind"] == "action"
    op: dict[str, Any] = {
        "operation_id": spec["operation_id"],
        "display_name": spec["display_name"],
        "description": spec["description"],
        "operation_kind": spec["kind"],
        "category": CATEGORY,
        "connection_type_ids": [CONNECTION_TYPE_ID],
        "workflow_visible": True,
    }
    if write:
        op["effect_kind"] = f"agnum_{spec['operation_id']}"
    effect_outputs = [
        {"name": "external_effect_status", "value_type": "text", "schema": {"type": "string"}},
        {
            "name": "definitely_no_external_effect",
            "value_type": "boolean",
            "schema": {"type": "boolean"},
        },
    ]
    outputs = list(spec["outputs"]) + (effect_outputs if write else [])
    op["inputs"] = [CONNECTION_INPUT, *(_clean(i) for i in spec["inputs"])]
    op["outputs"] = outputs
    op["result_fields"] = [f"result.{o['name']}" for o in outputs]
    op["error_codes"] = errors_for(spec)
    return op


