def coverage(steps: list[dict[str, Any]]) -> dict[str, Any]:
    everyday: dict[str, list[str]] = {}
    for spec in steps:
        if spec["group"] == "everyday":
            for call in spec.get("calls", []):
                everyday.setdefault(call, []).append(spec["operation_id"])
    stepped = {s["operation_id"] for s in steps}
    rows = []
    for row in plan.plan():
        call = f"{row['method']} {row['path']}"
        rows.append(
            {
                "method": row["method"],
                "path": row["path"],
                "operation_id": row["operation_id"],
                "title": row["title"],
                "kind": row["kind"],
                "status": "step" if row["operation_id"] in stepped else "missing",
                "danger": row["danger"],
                "objects": row["objects"],
                "no_effect": row["no_effect"],
                "rights": row["rights"],
                "codes": row["codes"],
                "release": row["release"],
                "everyday_steps": [s for s in everyday.get(call, []) if s != row["operation_id"]],
            }
        )
    return {"source": plan.facts()["source"], "endpoints": rows}


