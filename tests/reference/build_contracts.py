class _PageDumper(yaml.SafeDumper):
    """Multi-line strings as ``|`` blocks, so the page files read like markdown."""


def _represent_str(dumper: yaml.SafeDumper, value: str) -> yaml.ScalarNode:
    if "\n" in value:
        return dumper.represent_scalar("tag:yaml.org,2002:str", value, style="|")
    return dumper.represent_scalar("tag:yaml.org,2002:str", value)


_PageDumper.add_representer(str, _represent_str)


def _type_word(schema: dict[str, Any], value_type: str) -> str:
    if value_type == "artifact_handle":
        return "file"
    kinds = schema.get("type")
    kinds = [kinds] if isinstance(kinds, str) else list(kinds or [])
    kinds = [k for k in kinds if k != "null"]
    if schema.get("enum"):
        shown = ", ".join(str(v) for v in schema["enum"][:6])
        return "one of " + shown + (", …" if len(schema["enum"]) > 6 else "")
    if set(kinds) == {"number", "string"}:
        return "decimal"
    pattern = str(schema.get("pattern") or "")
    if kinds == ["string"] and pattern == ISO_DATE:
        return "date"
    if kinds == ["string"] and pattern in {DATE_TIME, WHEN}:
        return "date and time"
    if kinds == ["array"]:
        return "list"
    if "object" in kinds:
        return "record"
    return {"string": "text", "integer": "whole number", "boolean": "yes/no"}.get(
        kinds[0] if kinds else "", value_type
    )


def _describe(item: dict[str, Any], *, input_side: bool) -> str:
    schema = item.get("schema") or {}
    word = _type_word(schema, item.get("value_type", ""))
    required = input_side and item.get("required")
    flag = ", required" if required else ""
    description = str(schema.get("description") or "").strip()[:160]
    return f"- `{item['name']}` ({word}{flag}){': ' + description if description else ''}"


