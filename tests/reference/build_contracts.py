def answer_kind(op: dict[str, Any]) -> str:
    """record, list, boolean, object (a documented example only) or any (no usable schema)."""
    answer = op["answers"].get("200") or op["answers"].get("201") or {}
    schema = answer.get("schema") or {}
    if schema.get("ref"):
        return "record"
    kind = schema.get("type")
    if kind == "array":
        return "list"
    if kind == "boolean":
        return "boolean"
    if kind == "object" and schema.get("example"):
        return "object"
    return "any"


def _answer_ref(op: dict[str, Any]) -> str | None:
    answer = op["answers"].get("200") or op["answers"].get("201") or {}
    schema = answer.get("schema") or {}
    return schema.get("ref") or (schema.get("items") or {}).get("ref")


def _record_schema(op: dict[str, Any], description: str) -> dict[str, Any]:
    out: dict[str, Any] = {
        "type": "object",
        "additionalProperties": True,
        "description": description,
    }
    ref = _answer_ref(op)
    if ref:
        props = {}
        for name, spec in plan.schema(ref)["properties"].items():
            note = (spec.get("description") or "")[:150]
            if spec.get("deprecated"):
                note = (note + " Deprecated by Agnum.").strip()
            props[name] = {"description": note} if note else {}
        out["properties"] = props
    return out


def _data_output(op: dict[str, Any], description: str) -> dict[str, Any]:
    return {
        "name": "data",
        "value_type": "object",
        "schema": {
            **_record_schema(op, description),
            "type": ["object", "array", "boolean", "string", "number", "null"],
        },
    }


