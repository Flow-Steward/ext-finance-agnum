def _step_lines(spec: dict[str, Any]) -> list[str]:
    op = operation(spec)
    kind = "changes data" if spec["kind"] == "action" else "reads only"
    calls = ", ".join(f"`{c}`" for c in spec.get("calls", []))
    inputs = [i for i in op["inputs"] if i["name"] != "connection_ref"]
    return [
        f"### {spec['display_name']}",
        "",
        spec["description"],
        "",
        f"Action id `{spec['operation_id']}` · {kind} · Agnum: {calls}",
        "",
        "**Inputs**",
        "",
        *([_describe(i, input_side=True) for i in inputs] or ["- none"]),
        "",
        "**Results**",
        "",
        *[_describe(o, input_side=False) for o in op["outputs"] if o["name"] not in HIDDEN_RESULTS],
        "",
    ]


def _group_component(group: str, title: str, specs: list[dict[str, Any]]) -> dict[str, Any]:
    lines: list[str] = []
    shown = ""
    for spec in specs:
        if spec["danger"] != shown:
            shown = spec["danger"]
            lines += [_DANGER_HEADINGS[shown], ""]
        lines += _step_lines(spec)
    return {
        "component_id": "steps_" + group.lower().replace(" ", "_"),
        "type": "markdown",
        "title": title,
        "body": "\n".join(lines).strip() + "\n",
    }


def api_pages(steps: list[dict[str, Any]]) -> dict[str, dict[str, Any]]:
    titles = dict(GROUPS)
    by_group: dict[str, list[dict[str, Any]]] = {}
    for spec in steps:
        by_group.setdefault(spec["group"], []).append(spec)
    placed = [g for _, _, groups in API_PAGES for g in groups]
    if sorted(placed) != sorted(titles):  # pragma: no cover - a builder mistake
        raise SystemExit("every group must be on exactly one API page")
    index = []
    for _, page_title, groups in API_PAGES:
        count = sum(len(by_group.get(g, [])) for g in groups)
        names = ", ".join(titles[g] for g in groups)
        index.append(f"- **{page_title.split(' · ')[-1]}** ({count} steps): {names}.")
    overview = (
        "The steps reach the Agnum DB API at the address set in the connection, with its API "
        "key. Each step makes one documented call, except the everyday steps, which make two. "
        f"Every documented operation has a step: {len(steps)} steps in all.\n\n"
        "- **Rights.** Each step says which right its key needs (for example READ_KL to read "
        "clients, SAVE_VSK to create sales documents; READ_ALL, SAVE_ALL, EDIT_ALL and DEL_ALL "
        "cover all). A key without it is refused and nothing changes.\n"
        "- **Amounts are exact decimals.** They are sent as written, never rounded through "
        "binary floating point.\n"
        "- **Writes are sent once.** Flow Steward remembers every change it made, so a retried "
        "step does not send it twice, and test runs never send. When the outcome is unclear, "
        "the step is not retried: check Agnum first.\n"
        "- **Searches** compare every filter the same way (Compare: equals by default). "
        "Nothing found is an empty list.\n"
        f"- **{sum(1 for s in steps if s['danger'])} steps delete data**: replacing or changing "
        "a production or processing norm and deleting a norm. They take an explicit norm ID "
        "and come last in their section.\n\n"
        "The steps by area:\n\n" + "\n".join(index) + "\n"
    )
    pages: dict[str, dict[str, Any]] = {}
    for number, (page_id, page_title, groups) in enumerate(API_PAGES):
        components: list[dict[str, Any]] = []
        if number == 0:
            components.append(
                {
                    "component_id": "api_overview",
                    "type": "markdown",
                    "title": "How the steps work",
                    "body": overview,
                }
            )
        for group in groups:
            if by_group.get(group):
                components.append(_group_component(group, titles[group], by_group[group]))
        pages[f"ui/pages/{page_id}.yaml"] = {
            "page_id": page_id,
            "title": page_title,
            "description": f"Agnum steps: {', '.join(titles[g] for g in groups)}.",
            "components": components,
        }
    return pages


